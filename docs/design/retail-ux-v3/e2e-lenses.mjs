// Browser check of the eight-lens workspace (v3, English UI). Serve frontend/public on :8765 (python3 -m http.server 8765), then: node docs/design/retail-ux/e2e-lenses.mjs
import { chromium } from 'playwright';
const browser = await chromium.launch({ ...(process.env.PW_CHROMIUM ? { executablePath: process.env.PW_CHROMIUM } : {}), args: ['--use-gl=swiftshader','--enable-webgl','--ignore-gpu-blocklist'] });
const page = await browser.newPage({ viewport: { width: 1920, height: 1080 } });
const errs=[]; page.on('pageerror', e => errs.push(e.message));
await page.goto(process.env.FLOWFIELD_URL || 'http://localhost:8765/flowfield-v3/index.html?embed=1', { waitUntil: 'load' });
await page.waitForTimeout(11000);
const h2 = () => page.locator('.hx-inspector h2').first().innerText();
const hero = () => page.locator('.hx-leadkpi strong, .hx-hero strong').first().innerText().catch(()=>'-');
const tab = async (t) => { await page.locator('.hx-tabs button', { hasText: t }).first().click(); await page.waitForTimeout(2500); };
const ok=(c,m)=>console.log(c?'PASS':'FAIL', m);
await tab('Engagement');
await page.locator('.hx-barrow', { hasText: 'Vegetables' }).last().click(); await page.waitForTimeout(1500);
ok(await h2()==='Vegetables', 'ranking click selects Vegetables: '+await h2());
ok((await hero())==='53 s', 'Vegetables area minutes from daily_kpi (0.88 min): '+await hero());
ok(await page.locator('.hx-call.sel, .hx-call.lead').count()>0, 'selected area called out on the map');
await tab('Pulse'); await tab('Engagement');
ok(await h2()==='Vegetables', 'selection kept Pulse→Engagement');
await tab('Live');
ok(await page.locator('.hx-inspector select').inputValue()==='Verdura', 'Live region keeps the Vegetables id');
ok((await page.locator('.hx-now').count())===1, 'Live clock NOW');
await tab('Service');
ok(!/Vegetables/.test(await h2()), 'dept selection cleared on Service: '+await h2());
await page.locator('.hx-slots button', { hasText: '18–20' }).click(); await page.waitForTimeout(1500);
ok(await hero()==='1 min 1 s', 'slot 18–20 queue per customer: '+await hero());
await page.locator('.hx-bars .hx-barrow').first().click(); await page.waitForTimeout(1500);
ok(await h2()==='Lane 5', 'top waiting lane is Lane 5: '+await h2());
await page.locator('.hx-source button', { hasText: 'Executive report' }).click(); await page.waitForTimeout(2500);
ok((await page.locator('.hx-badge').innerText()).includes('ARCHIVED'), 'exec source labelled archived');
ok((await hero())==='26 s', 'exec channel avg wait 26 s: '+await hero());
await page.locator('.hx-bars .hx-barrow', { hasText: 'Checkout 4' }).click(); await page.waitForTimeout(1500);
ok((await hero())==='54 s', 'Checkout 4 54 s: '+await hero());
await tab('Engagement');
ok((await hero())==='70.0%', 'exec Verdura stopping 70%: '+await hero());
ok((await page.locator('.hx-pill.kpi').innerText()).includes('00:00–23:30'), 'report window chip');
await page.locator('.hx-source button', { hasText: 'Visitor Journey' }).click(); await page.waitForTimeout(1500);
ok((await page.locator('.hx-pill.kpi').innerText()).includes('Visitor Journey'), 'back to Visitor Journey');
await tab('Compare');
ok(await page.locator('.hx-cmp-strip canvas').count()===6 && await page.locator('.hx-cmp-main canvas').count()===1, 'compare: one large map + six-slot filmstrip');
const h2a = await h2(); await page.locator('.hx-bar .hx-play').click(); await page.waitForTimeout(4200);
ok((await h2()) !== h2a && (await page.locator('.hx-cmp-strip button.active').count())===1, 'play walks the day: '+h2a+' → '+await h2());
await page.locator('.hx-bar .hx-play').click();
await page.locator('.hx-layer-seg button', { hasText: 'A vs B' }).click(); await page.waitForTimeout(2500);
ok(await page.locator('.hx-compare canvas').count()===2, 'A vs B: two matched maps');
await page.locator('.hx-layer-seg button', { hasText: 'Difference' }).click(); await page.waitForTimeout(2500);
ok(await page.locator('.hx-compare canvas').count()===1, 'difference map');
await tab('Opportunities');
ok((await page.locator('.hx-inspector .hx-bars .hx-barrow').count())>=8, 'value at stake lists many areas: '+await page.locator('.hx-inspector .hx-bars .hx-barrow').count());
ok((await page.locator('.hx-money').first().innerText()).includes('€'), 'modelled € range shown: '+await page.locator('.hx-money').first().innerText());
await page.locator('.hx-inspector .hx-barrow', { hasText: 'Meat counter' }).click(); await page.waitForTimeout(1000);
ok((await h2())==='Meat counter', 'select Meat counter');
await tab('Pulse');
await page.locator('.hx-slots button', { hasText: '08–10' }).click(); await page.waitForTimeout(4000);
ok((await page.locator('.hx-pill.flow').innerText()).includes('08–10'), 'floor follows the slot: '+await page.locator('.hx-pill.flow').innerText());
await tab('Flow Explorer');
for (const l of ['Dwell','Direction','Regimes','Movement']) { await page.locator('.hx-layer-seg button', { hasText: l }).click(); await page.waitForTimeout(2000); }
ok(true, 'flow layers switched');
await tab('Behaviour');
ok((await page.locator('.hx-pill.kin').innerText()).includes('10 Hz'), 'behaviour: measured movement chip');
ok((await page.locator('.hx-inspector .hx-state').count())===6, 'behaviour: six states in the store mix');
ok((await page.locator('.hx-legend .hx-lchip').count())===6, 'behaviour: clickable state legend');
await page.locator('.hx-layer-seg button', { hasText: 'Department fingerprints' }).click(); await page.waitForTimeout(2000);
ok((await page.locator('.hx-donut').count())>=8, 'behaviour: department rings on the floor: '+await page.locator('.hx-donut').count());
await page.locator('.hx-donut', { hasText: 'FROZEN' }).first().click(); await page.waitForTimeout(1500);
ok((await h2())==='Frozen' && (await page.locator('.hx-lead').first().innerText()).includes('choose'), 'behaviour: Frozen fingerprint reads as choosing: '+await page.locator('.hx-lead').first().innerText());
ok((await page.locator('.kin-val').innerText()).includes('0.996'), 'behaviour: validation r against al banco shown');
await page.locator('.hx-layer-seg button', { hasText: 'Hesitation spots' }).click(); await page.waitForTimeout(2000);
ok((await page.locator('.hx-hot').count())>=3, 'behaviour: hesitation spots: '+await page.locator('.hx-hot').count());
await page.locator('.hx-slots button', { hasText: '18–20' }).click(); await page.waitForTimeout(3000);
ok((await page.locator('.hx-pill.kin').innerText()).includes('18–20'), 'behaviour follows the slot');
await tab('Opportunities');
ok((await page.locator('.hx-inspector .hx-card.obs').innerText()).includes('Moving past (10 Hz)'), 'opportunities: measured movement in the observed evidence');
ok((await page.locator('.hx-inspector').innerText()).includes('MODELLED SCENARIO') && !(await page.locator('.hx-inspector').innerText()).toLowerCase().includes('recoverable margin'), 'opportunities: scenario labelled modelled, no recoverable claim');
await tab('Compare');
await page.locator('.hx-layer-seg button', { hasText: 'The day' }).click(); await page.waitForTimeout(1500);
await page.locator('.hx-inspector .hx-seg button', { hasText: 'Behaviour' }).click(); await page.waitForTimeout(2500);
ok((await page.locator('.hx-cmp-strip canvas').count())===6 && (await page.locator('.hx-cmp-note').innerText()).includes('movement state'), 'compare: the day by behaviour');
await page.locator('.hx-top-r button', { hasText: 'Lab' }).click(); await page.waitForTimeout(500);
ok(await page.locator('#controls').isVisible(), 'Lab drawer opens engineering controls');
console.log('errors:', errs.slice(0,5));
await browser.close();
